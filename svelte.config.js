import adapter from '@sveltejs/adapter-static';
import { vitePreprocess } from '@sveltejs/vite-plugin-svelte';
import pkg from './package.json' with { type: 'json' };

// BASE_PATH is empty for the custom domain (barchy.ovadi.nl); set it for a project page such as /BARCHY.
const base = process.env.BASE_PATH ?? '';

/** @type {import('@sveltejs/kit').Config} */
const config = {
	preprocess: vitePreprocess(),
	kit: {
		adapter: adapter({ fallback: '404.html', strict: true }),
		paths: { base, relative: false },
		// Shown on About; also lets the app notice a new deploy.
		version: { name: pkg.version },
		prerender: { handleHttpError: 'fail', handleMissingId: 'fail' },
		// The service worker is generated by @vite-pwa/sveltekit, not by SvelteKit.
		serviceWorker: { register: false }
	}
};

export default config;
